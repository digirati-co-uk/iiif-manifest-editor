import { readFile, writeFile, mkdir } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { scanModule } from "./inventory-source.mjs";
import { modulePlans } from "../implementation/module-plans.mjs";

const { values } = parseArgs({ options: { check: { type: "boolean" } } });
const root = fileURLToPath(new URL("../../../", import.meta.url));
const rootUrl = new URL("../../../", import.meta.url);
const sourceFiles = [
  ...new Set(
    execFileSync("git", ["ls-files", "--cached", "--others", "--exclude-standard", "-z"], {
      cwd: root,
      encoding: "utf8",
    })
      .split("\0")
      .filter(Boolean)
  ),
];
const revision = execFileSync("git", ["rev-parse", "HEAD"], { cwd: root, encoding: "utf8" }).trim();
const destination = new URL("../implementation/inventories/", import.meta.url);
const sourceLink = (file, line) =>
  `../../../../${file
    .split("/")
    .map((part) => encodeURIComponent(part).replace(/\(/g, "%28").replace(/\)/g, "%29"))
    .join("/")}${line ? `#L${line}` : ""}`;
const escape = (value) =>
  String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/\|/g, "\\|")
    .replace(/`/g, "'")
    .replace(/\s+/g, " ")
    .trim();
const table = (rows) =>
  [
    "| File | Candidate occurrences |",
    "| --- | ---: |",
    ...rows.map(({ name, count }) => `| [${name}](${sourceLink(name)}) | ${count} |`),
  ].join("\n");
const outputs = [];
const summaries = [];

for (const plan of modulePlans.filter((plan) => plan.path && plan.id !== "00-languages")) {
  if (!sourceFiles.includes(`${plan.path}/package.json`)) throw new Error(`Module manifest is missing: ${plan.path}`);
  const { primary, supporting } = await scanModule(rootUrl, plan.path, sourceFiles, revision);
  if (primary.errors.length || supporting.errors.length) throw new Error(`Incomplete audit: ${plan.path}`);
  summaries.push({
    id: plan.id,
    path: plan.path,
    revision: primary.revision,
    primary: primary.summary,
    includingSupportingSource: supporting.summary,
  });
  const lines = [
    `# ${plan.title} source inventory`,
    "",
    `Module: \`${plan.path}\`. Revision: \`${primary.revision}\`. [Implementation task](../modules/${plan.id}.md).`,
    "",
    `Default application-source scan: **${primary.summary.candidateOccurrences} occurrences** in **${primary.summary.filesWithCandidates} files** (${primary.summary.filesScanned} files scanned). Expanded JS/TS scan including tests/stories/tutorials/examples: **${supporting.summary.candidateOccurrences} occurrences**.`,
    "",
    "These are syntactic candidates, not final message IDs or verified active UI. Scans use git's tracked/unignored files and exclude generated, public and vendor assets. Supporting-source strings are usually fixtures or assertions, not catalog entries. Markdown/MDX/JSON/CSS and third-party UI are not included. Review authored defaults and developer errors before extraction. Mixed JSX may be fragments of one whole message. Text below is shortened to 180 characters; follow the source link for the original.",
    "",
    "## Default application source files",
    "",
    table(primary.byFile),
    "",
    "## Expanded review list",
    "",
  ];
  for (const row of supporting.byFile) {
    lines.push(
      `### ${row.name}`,
      "",
      `- [ ] Review [source](${sourceLink(row.name)}) and classify its ${row.count} candidates.`,
      "",
      "| Line | Kind | Candidate text | Complexity flags |",
      "| ---: | --- | --- | --- |"
    );
    for (const item of supporting.candidates.filter((item) => item.file === row.name))
      lines.push(
        `| [${item.line}](${sourceLink(item.file, item.line)}) | ${item.kind} | ${escape(item.text.slice(0, 180))} | ${item.flags.join(", ") || "—"} |`
      );
    lines.push("");
  }
  if (!supporting.candidates.length)
    lines.push(
      "No candidates detected. Manually inspect errors, response text, dependencies and non-JS/TS assets before marking the module reviewed.",
      ""
    );
  if (supporting.risks.length) {
    lines.push(
      "## Formatting and content-language review points",
      "",
      "| Source | Review kind | Code |",
      "| --- | --- | --- |"
    );
    for (const item of supporting.risks)
      lines.push(
        `| [${item.file}:${item.line}](${sourceLink(item.file, item.line)}) | ${item.kind} | ${escape(item.code)} |`
      );
    lines.push("");
  }
  outputs.push([`${plan.id}.md`, lines.join("\n")]);
}

outputs.push(["summary.json", JSON.stringify(summaries, null, 2) + "\n"]);
outputs.push([
  "README.md",
  [
    "# Module source inventories",
    "",
    "Generated by `npm run inventory` in this package. This reads repository source and writes only this inventory directory. Task guides are maintained separately and are never overwritten. Use `npm run inventory -- --check` to detect stale inventories without writing.",
    "",
    "| Module | Application candidates | Expanded candidates | Review |",
    "| --- | ---: | ---: | --- |",
    ...summaries.map(
      (item) =>
        `| ${item.path} | ${item.primary.candidateOccurrences} | ${item.includingSupportingSource.candidateOccurrences} | [Inventory](${item.id}.md) |`
    ),
    "",
    "Expanded counts include supporting JS/TS source; they do not estimate documentation prose translation. Scans respect git ignores and omit generated/public/vendor assets. A zero count is not a completion claim. The classifier comes from the repository's existing scripts/audit-i18n.mjs; runtime package code does not depend on that tooling.",
    "",
  ].join("\n"),
]);

let changed = 0;
for (const [name, contents] of outputs) {
  const url = new URL(name, destination);
  let previous;
  try {
    previous = await readFile(url, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (previous === contents) continue;
  changed++;
  if (values.check) console.error(`Stale inventory: ${name}`);
  else {
    await mkdir(destination, { recursive: true });
    await writeFile(url, contents);
  }
}
console.log(
  `${values.check ? "Checked" : "Generated"} ${summaries.length} module inventories; ${changed} ${values.check ? "stale" : "updated"} files.`
);
if (values.check && changed) process.exitCode = 1;
