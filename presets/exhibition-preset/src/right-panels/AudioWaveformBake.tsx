import { useEffect, useRef, useState } from "react";
import { useCanvas, useVault } from "react-iiif-vault";
import {
  createWaveformBakeJob,
  generateBakedWaveform,
  getBakedWaveform,
  getCanvasSound,
  saveBakedWaveform,
} from "../audio-waveform-baking";
import {
  AudioAlert,
  AudioButton,
  AudioHint,
  AudioPanelSection,
  AudioStatus,
  simpleLayoutColours,
} from "./AudioPanelParts";

export function AudioWaveformBake() {
  const canvas = useCanvas();
  const vault = useVault();
  const sound = getCanvasSound(vault, canvas);
  const saved = getBakedWaveform(vault, canvas);
  const job = useRef(createWaveformBakeJob());
  const [progress, setProgress] = useState<number | null>(null);
  const [error, setError] = useState("");
  const [complete, setComplete] = useState(false);
  useEffect(() => {
    const currentJob = job.current;
    setProgress(null);
    setError("");
    setComplete(false);
    return () => currentJob.cancel();
  }, [canvas?.id, sound?.id]);
  if (!canvas || !sound) return null;

  const generate = async () => {
    const run = job.current.start();
    setError("");
    setComplete(false);
    setProgress(0);
    try {
      const peaks = await generateBakedWaveform(sound.id, {
        signal: run.signal,
        duration: sound.duration || canvas.duration,
        onProgress: (value) => {
          if (run.isCurrent()) setProgress(value);
        },
      });
      if (!run.isCurrent()) return;
      saveBakedWaveform(vault, canvas.id, peaks);
      setComplete(true);
    } catch (failure) {
      if (run.isCurrent())
        setError(
          failure instanceof TypeError
            ? "The recording could not be read. Its server must allow cross-origin (CORS) access."
            : failure instanceof Error
              ? failure.message
              : "Could not generate the waveform."
        );
    } finally {
      if (run.isCurrent()) setProgress(null);
    }
  };
  const cancel = () => {
    job.current.cancel();
    setProgress(null);
  };

  return (
    <AudioPanelSection
      title="Saved waveform"
      label="Saved audio waveform"
      description="Without a saved waveform, each visitor's browser downloads and decodes the whole recording to draw it. Saving one stores a small set of peaks inside the manifest."
    >
      {saved ? (
        <AudioStatus tone="ok">Waveform saved inside the manifest</AudioStatus>
      ) : (
        <AudioStatus tone="muted">No saved waveform — generated by the viewer when needed</AudioStatus>
      )}
      {progress !== null ? (
        <div className="flex flex-col gap-2">
          <label
            className="text-xs font-semibold"
            htmlFor="audio-waveform-generation"
            style={{ color: simpleLayoutColours.text }}
          >
            Generating waveform — {Math.round(progress * 100)}%
          </label>
          <progress
            id="audio-waveform-generation"
            max={1}
            value={progress}
            className="w-full accent-me-primary-500"
          />
          <AudioHint>Reading and decoding audio may take a moment. Cancelling discards this run.</AudioHint>
          <AudioButton className="self-start" onClick={cancel}>
            Cancel generation
          </AudioButton>
        </div>
      ) : (
        <div className="flex flex-wrap gap-2">
          <AudioButton variant={saved ? "secondary" : "primary"} onClick={generate}>
            {saved ? "Regenerate waveform" : "Generate waveform"}
          </AudioButton>
          {saved ? (
            <AudioButton
              variant="danger"
              onClick={() => {
                job.current.cancel();
                saveBakedWaveform(vault, canvas.id, null);
                setComplete(false);
              }}
            >
              Remove saved waveform
            </AudioButton>
          ) : null}
        </div>
      )}
      <AudioHint>Runs in this browser, no upload. Up to 48 MB and 45 minutes; the audio server must allow CORS.</AudioHint>
      {complete ? <output className="text-xs font-semibold text-green-800">Waveform saved inside the manifest.</output> : null}
      {error ? <AudioAlert>{error}</AudioAlert> : null}
    </AudioPanelSection>
  );
}
